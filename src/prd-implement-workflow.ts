  '          [ -n "$result" ] || exit 1',
  '          jq -e \'.status == "completed" and (.iterations as $last | [.checks[] | select(.iteration == $last)] | length > 0) and (.iterations as $last | [.checks[] | select(.iteration == $last and .exitCode != 0)] | length == 0)\' "$result" >/dev/null',
  '          [ -s "$RUNNER_TEMP/prd-result/export/change.patch" ] || exit 1',
  "      - uses: actions/checkout@v4",
  "        with:",
  "          ref: ${{ steps.branch.outputs.ref }}",
  "          persist-credentials: false",
  "          fetch-depth: 0",
  "      - name: Apply patch and advance PRD",
  "        env:",
  "          PRD_TITLE: ${{ github.event.issue.title }}",
  "        run: |",
  "          set -euo pipefail",
  '          base=$(cat "$RUNNER_TEMP/prd-result/export/base-sha.txt")',
  '          [ "$(git rev-parse HEAD)" = "$base" ] || { echo \'PRD branch advanced\' >&2; exit 1; }',
  '          git switch -c "$BRANCH" 2>/dev/null || git switch "$BRANCH"',
  '          git apply --check "$RUNNER_TEMP/prd-result/export/change.patch"',
  '          git apply "$RUNNER_TEMP/prd-result/export/change.patch"',
