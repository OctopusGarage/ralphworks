  "",
  "on:",
  "  issues:",
  "    types: [labeled]",
  "",
  "concurrency:",
  "  group: ralphworks-prd-implement-${{ github.event.issue.number }}",
  "  cancel-in-progress: false",
  "",
  "jobs:",
  "  implement:",
