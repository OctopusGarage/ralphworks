  "name: RalphWorks Split PRD",
  "",
  "on:",
  "  issues:",
  "    types: [labeled]",
  "",
  "concurrency:",
  "  group: ralphworks-prd-split-${{ github.event.issue.number }}",
  "  cancel-in-progress: false",
  "",
  "jobs:",
  "  split:",
