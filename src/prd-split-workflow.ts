  "    runs-on: ubuntu-latest",
  "    timeout-minutes: 40",
  "    permissions:",
  "      contents: read",
  "      issues: read",
  "    env:",
  "      GH_TOKEN: ${{ github.token }}",
  "      GH_REPO: ${{ github.repository }}",
  "      ISSUE_NUMBER: ${{ github.event.issue.number }}",
  "      LABEL_ACTOR: ${{ github.event.sender.login }}",
